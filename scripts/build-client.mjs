#!/usr/bin/env node
/**
 * Wrap `src/client.js` in the client-module envelope and write `lib/client.js`.
 *
 * The envelope is the contract the DSH client module system reads from a
 * package's `exports["./client"]` bundle: registration-time code only calls
 * `window.__ModuleLoader__.load`, and the plugin body materializes on first
 * import. Keeping it generated means the readable source stays plain and the
 * shipped artifact stays in the exact shape the loader expects.
 *
 * Usage:
 *   node scripts/build-client.mjs          # (re)write lib/client.js
 *   node scripts/build-client.mjs --check  # exit 1 when the artifact is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const packageName = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).name;
const source = readFileSync(join(root, "src/client.js"), "utf8").replace(/\n+$/u, "");
const artifactPath = join(root, "lib/client.js");

/** Indent every line of `body` by one tab. */
const indent = (body) =>
	body
		.split("\n")
		.map((line) => (line === "" ? line : `\t${line}`))
		.join("\n");

const artifact = `// Generated by scripts/build-client.mjs from src/client.js; do not edit.
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(packageName)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${indent(source)}
\t\treturn module.exports;
\t}
});
`;

if (process.argv.includes("--check")) {
	let current;
	try {
		current = readFileSync(artifactPath, "utf8");
	} catch {
		current = "";
	}
	if (current !== artifact) {
		console.error("client bundle is stale: run `npm run build:client`");
		process.exit(1);
	}
	console.log("client bundle is up to date");
} else {
	writeFileSync(artifactPath, artifact);
	console.log(`wrote ${artifactPath}`);
}
